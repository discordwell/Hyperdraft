def _families(events):
    """Map emitted events to effect-family tokens (mirrors the detector)."""
    fams = []
    for e in events:
        n = e.type.name if hasattr(e.type, "name") else str(e.type)
        pl = e.payload or {}
        if n == "CREATE_TOKEN" or (n == "OBJECT_CREATED" and pl.get("is_token")):
            fams.append("CREATE_TOKEN")
        elif n == "LIFE_CHANGE":
            fams.append("GAINLIFE" if pl.get("amount", 0) > 0 else "LOSELIFE")
        elif n == "ACTIVATE" and pl.get("action") == "scry":
            fams.append("SCRY")
        elif n in ("ZONE_CHANGE", "OBJECT_DESTROYED", "PHASE_START",
                   "ATTACK_DECLARED", "BLOCK_DECLARED", "VOID_ACTIVATED",
                   "TARGET_REQUIRED"):
            pass
        else:
            fams.append(n)
    return fams


def _fire(card_name, kind):
    """Build a minimal 2-player board, drop the card in, fire `kind` trigger,
    return emitted effect-families."""
    cd = ATTACK_ON_TITAN_CARDS[card_name]
    game = Game()
    p1 = game.add_player("Alice")
    p2 = game.add_player("Bob")
    obj = game.create_object(
        name=cd.name, owner_id=p1.id, zone=ZoneType.BATTLEFIELD,
        characteristics=cd.characteristics, card_def=cd,
    )
    # An opponent permanent so drain/damage-per-ally templates have a target.
    pure = ATTACK_ON_TITAN_CARDS["Pure Titan"]
    game.create_object(
        name="OppC", owner_id=p2.id, zone=ZoneType.BATTLEFIELD,
        characteristics=pure.characteristics, card_def=pure,
    )
    for itc in (cd.setup_interceptors(obj, game.state) or []):
        obj.interceptor_ids.append(itc.id)
        game.state.interceptors[itc.id] = itc
    game.state.active_player = p1.id
    payloads = {
        "etb": Event(type=EventType.ZONE_CHANGE,
                     payload={"object_id": obj.id, "from_zone_type": ZoneType.HAND,
                              "to_zone_type": ZoneType.BATTLEFIELD},
                     source=obj.id, controller=p1.id),
        "death": Event(type=EventType.OBJECT_DESTROYED,
                       payload={"object_id": obj.id}, source=obj.id, controller=p1.id),
        "attack": Event(type=EventType.ATTACK_DECLARED,
                        payload={"attacker_id": obj.id, "defender_id": p2.id},
                        source=obj.id, controller=p1.id),
        "upkeep": Event(type=EventType.PHASE_START,
                        payload={"phase": "upkeep"}, source=obj.id, controller=p1.id),
        "block": Event(type=EventType.BLOCK_DECLARED,
                       payload={"blocker_id": obj.id, "attacker_id": "x"},
                       source=obj.id, controller=p1.id),
    }
    return _families(game.emit(payloads[kind]))


def _check(card_name):
    kind, expected = CARD_EXPECTATIONS[card_name]
    fams = _fire(card_name, kind)
    assert fams, f"{card_name}: {kind} trigger emitted no events (expected one of {expected})"
    assert any(f in expected for f in fams), (
        f"{card_name}: {kind} trigger emitted {sorted(set(fams))}, "
        f"expected one of {expected} (text: {ATTACK_ON_TITAN_CARDS[card_name].text!r})"
    )


