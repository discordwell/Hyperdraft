"""
Smoke tests for CLAN — generated by scripts/new_set/wire_set.py.

Asserts:
  - every card in the set imports without error
  - every card has a CardDefinition with name + characteristics
  - every starter deck builder runs without raising and returns a
    non-empty list of CardDefinitions

The "every card actually resolves in play" guarantee is enforced by the
balance-loop coverage stage (scripts/new_set/balance_loop.py +
scripts/new_set/coverage.py), which can detect missing implementations
via zero-play cards across the tournament — that check is engine-aware
where this scaffold is engine-agnostic by design.
"""

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from src.cards.clankers.CLAN import CLAN_CARDS, build_clan_forge, build_clan_ethos, build_clan_mirth, build_clan_bulwark


def test_every_card_loads():
    assert CLAN_CARDS, "CLAN card registry is empty"
    for name, card in CLAN_CARDS.items():
        assert card is not None, f"{name}: card def is None"
        assert card.name, f"{name}: card has no .name"
        assert card.characteristics is not None, \
            f"{name}: card has no .characteristics"


def _assert_clankers_deck(builder, label):
    """Clankers builders return (core, deck_list)."""
    core, deck = builder()
    assert core is not None, f"{label}: missing Core"
    assert core.name, f"{label}: Core has no .name"
    assert len(deck) == 60, f"{label}: deck has {len(deck)} cards (expected 60)"
    for cd in deck:
        assert cd is not None, f"{label}: contains a None card"
        assert getattr(cd, "name", None), f"{label}: contains a nameless card"


def test_deck_forge_builds():
    _assert_clankers_deck(build_clan_forge, "forge")


def test_deck_ethos_builds():
    _assert_clankers_deck(build_clan_ethos, "ethos")


def test_deck_mirth_builds():
    _assert_clankers_deck(build_clan_mirth, "mirth")


def test_deck_bulwark_builds():
    _assert_clankers_deck(build_clan_bulwark, "bulwark")



if __name__ == "__main__":
    test_every_card_loads()
    test_deck_forge_builds()
    test_deck_ethos_builds()
    test_deck_mirth_builds()
    test_deck_bulwark_builds()
    print("OK — CLAN smoke tests pass.")
